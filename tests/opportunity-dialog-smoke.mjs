import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {openDesktopMenu} from './menu-helper.mjs';
import {fillOpportunityProfile} from './opportunity-profile-browser.mjs';
const browser=await chromium.launch({headless:true});
await mkdir('test-artifacts',{recursive:true});
const site=process.env.SITE_URL||'http://127.0.0.1:4173/kc-kuto-crm/';
const moduleUrl=new URL('src/internal-workspace.mjs?v=20261001-opportunity-popup',site).href;
try{
  for(const width of [1440,390]){
    const page=await browser.newPage({viewport:{width,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(site);
    await page.getByRole('button',{name:'เข้าใช้งานโหมดทดลอง',exact:true}).click();
    await page.getByRole('button',{name:'เปลี่ยนเป็นภาษาอังกฤษ',exact:true}).click();
    const open=async(parent,child)=>{
      if(width>=1024)return openDesktopMenu(page,parent,child);
      await page.locator('button.lg\\:hidden').first().click();
      const sidebar=page.locator('div.fixed.top-0.left-0.h-full.w-64.lg\\:hidden');
      if(!await sidebar.getByText(parent,{exact:true}).isVisible())await sidebar.getByRole('button',{name:'Sales',exact:true}).click();
      if(!await sidebar.getByText(child,{exact:true}).isVisible())await sidebar.getByText(parent,{exact:true}).click();
      await sidebar.getByText(child,{exact:true}).click();
    };
    await page.evaluate(async url=>{
      const {DEMO_RECORDS:demo}=await import(url);
      demo.customers=[{id:'a',code:'CUS-A',name:'QA Alpha',name_en:'Alpha Company',status:'Active'},{id:'b',code:'CUS-B',name:'QA Beta',status:'Active'}];
      demo.contacts=[{id:'ca',name:'Alpha Contact',customer_id:'a',status:'active'},{id:'cb',name:'Beta Contact',customer_id:'b',status:'active'}];
      demo.opportunities=[];
    },moduleUrl);
    await open('Opportunities',width>=1024?'Opportunity List':'Pipeline Kanban');
    const root=page.locator('[data-entity="opportunities"]');
    if(width<1024)await root.getByRole('button',{name:'Table',exact:true}).click();
    await root.getByRole('button',{name:'Create opportunity',exact:true}).click();
    let form=root.getByRole('form',{name:'Opportunity form'});
    await form.waitFor();
    assert.equal(await root.locator('dialog').evaluate(el=>el.matches(':modal')),true);
    for(const label of ['Opportunity Name','Account Name','Close Date','Stage','Forecast Category'])assert.equal(await form.getByLabel(label,{exact:true}).getAttribute('required'),'');
    await form.getByRole('button',{name:'Save',exact:true}).click();
    assert.equal(await form.locator(':invalid').count()>0,true);
    await form.getByLabel('Opportunity Name',{exact:true}).fill('QA Linked Deal');
    await fillOpportunityProfile(form,'QA Alpha');
    await form.getByText('Additional CRM Information',{exact:true}).click();
    const contact=form.getByLabel('Contact',{exact:true});
    assert.deepEqual(await contact.locator('option').allTextContents(),['--None--','Alpha Contact']);
    await contact.selectOption('ca');
    await form.getByRole('combobox',{name:'Account Name',exact:true}).fill('CUS-B');
    await form.getByRole('option',{name:/QA Beta/}).click();
    assert.equal(await contact.inputValue(),'');
    assert.deepEqual(await contact.locator('option').allTextContents(),['--None--','Beta Contact']);
    await form.getByRole('combobox',{name:'Account Name',exact:true}).fill('Alpha');
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    await contact.selectOption('ca');
    const owner=await form.getByLabel('Opportunity Owner',{exact:true}).inputValue();
    await page.screenshot({path:`test-artifacts/opportunity-popup-${width}.png`,fullPage:true});
    await form.getByRole('button',{name:'Save & New',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('form[aria-label="Opportunity form"] input[aria-label="Opportunity Name"]')?.value==='');
    form=root.getByRole('form',{name:'Opportunity form'});
    for(const label of ['Opportunity Name','Account Name','Close Date','Description','Stage','Forecast Category','Next Step'])assert.equal(await form.getByLabel(label,{exact:true}).inputValue(),'');
    assert.equal(await form.getByLabel('Opportunity Owner',{exact:true}).inputValue(),owner);
    let saved=await page.evaluate(async url=>(await import(url)).DEMO_RECORDS.opportunities,moduleUrl);
    assert.equal(saved.length,1);assert.equal(saved[0].customer_id,'a');assert.equal(saved[0].contact_id,'ca');assert.equal(saved[0].owner_id,owner);assert.equal(saved[0].weighted_amount,72000.3);assert.equal(saved[0].solution,'Linked opportunity description');assert.equal(saved[0].next_action,'Schedule customer review');
    await form.getByLabel('Opportunity Name',{exact:true}).fill('QA cancelled');
    await page.keyboard.press('Escape');
    await form.waitFor({state:'hidden'});
    assert.equal(await page.evaluate(async url=>(await import(url)).DEMO_RECORDS.opportunities.length,moduleUrl),1);
    await root.getByRole('button',{name:'Table',exact:true}).click();
    await root.getByRole('button',{name:/^Details /}).first().click();
    await root.getByRole('button',{name:'Edit',exact:true}).click();
    await form.waitFor();
    assert.equal(await form.getByLabel('Account Name',{exact:true}).inputValue(),'QA Alpha');
    assert.equal(await form.getByLabel('Description',{exact:true}).inputValue(),'Linked opportunity description');
    assert.equal(await form.getByLabel('Stage',{exact:true}).inputValue(),'Proposal');
    await form.getByLabel('Stage',{exact:true}).selectOption('Won');
    assert.equal(await form.getByLabel('Probability (%)',{exact:true}).inputValue(),'100');
    assert.equal(await form.getByLabel('Forecast Category',{exact:true}).inputValue(),'Closed Won');
    await form.getByRole('button',{name:'Save',exact:true}).click();
    await form.waitFor({state:'hidden'});
    saved=await page.evaluate(async url=>(await import(url)).DEMO_RECORDS.opportunities,moduleUrl);
    assert.equal(saved[0].status,'won');assert.equal(saved[0].weighted_amount,120000.5);
    await root.getByRole('button',{name:'Edit',exact:true}).click();
    await form.getByLabel('Stage',{exact:true}).selectOption('Lost');
    await form.getByRole('button',{name:'Save',exact:true}).click();
    assert.equal(await form.getByLabel('Lost Reason',{exact:true}).evaluate(el=>el.validity.valueMissing),true);
    await form.getByLabel('Lost Reason',{exact:true}).fill('Budget');
    await form.getByRole('button',{name:'Save',exact:true}).click();
    await form.waitFor({state:'hidden'});
    saved=await page.evaluate(async url=>(await import(url)).DEMO_RECORDS.opportunities,moduleUrl);
    assert.equal(saved[0].status,'lost');assert.equal(saved[0].probability,0);assert.equal(saved[0].forecast_category,'Closed Lost');assert.equal(saved[0].weighted_amount,0);
    await root.getByRole('button',{name:'Open Account',exact:true}).click();
    const accountDetail=page.locator('[data-entity="customers"]').getByRole('region',{name:'Record details'});
    await accountDetail.getByRole('heading',{name:'CUS-A',exact:true}).waitFor();
    await accountDetail.getByRole('heading',{name:'Opportunities (1)',exact:true}).locator('..').getByRole('button').click();
    await root.getByRole('region',{name:'Record details'}).waitFor();
    assert.deepEqual(errors,[]);
    console.log(`PASS opportunity popup ${width}px: required fields, account search/keyboard, contact isolation, Save & New reset, cancel, edit, won/lost consistency and bidirectional account link; demo data only`);
    await page.close();
  }
}finally{await browser.close();}
